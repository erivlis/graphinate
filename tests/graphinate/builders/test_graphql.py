def test_graphql_builder_weakly_connected_components_and_neighbor_type_filter():
    import strawberry

    from graphinate.enums import GraphType

    m = graphinate.model("DirectedModel")

    @m.node()
    def service():
        yield "svc1"

    @m.node(parent_type="service")
    def endpoint(service_id):
        yield f"{service_id}/ep1"

    @m.node(parent_type="service")
    def database(service_id):
        yield f"{service_id}/db1"

    builder = graphinate.builders.GraphQLBuilder(m, graph_type=GraphType.DiGraph)

    @strawberry.type
    class ServiceValue:
        name: str

    schema = builder.build(
        node_value_graphql_type_supplier=lambda nt: strawberry.scalars.JSON if nt == "service" else None
    )

    query = """
    {
      weakly: measure(measure: number_weakly_connected_components) {
        name
        value
      }
      services {
        label
        epNeighbors: neighbors(type: endpoint) {
          type
          label
        }
      }
    }
    """
    result = schema.execute_sync(query)
    assert result.errors is None
    assert result.data == {
        "weakly": {
            "name": "number_weakly_connected_components",
            "value": 1,
        },
        "services": [
            {
                "label": "svc1",
                "epNeighbors": [
                    {
                        "type": "endpoint",
                        "label": "svc1/ep1",
                    }
                ],
            }
        ],
    }


def test_graphql_builder_enum_isolation_and_reserved_identifiers():
    m1 = graphinate.model("FirstModel")

    @m1.node()
    def alpha():
        yield "a1"

    schema1 = graphinate.builders.GraphQLBuilder(m1).build()
    assert schema1 is not None

    m2 = graphinate.model("SecondModel")

    @m2.node(type_="list")
    def list_nodes():
        yield "item1"

    builder2 = graphinate.builders.GraphQLBuilder(m2)
    schema2 = builder2.build()

    introspection = schema2.execute_sync(
        '{ __type(name: "GraphNodeType") { enumValues { name } } }'
    )
    assert introspection.errors is None
    enum_names = [ev["name"] for ev in introspection.data["__type"]["enumValues"]]
    assert enum_names == ["list_"]
    assert "alpha" not in enum_names

    custom_enum = graphinate.builders.GraphQLBuilder._graphql_enum("CustomEnum", ["class", "123"])
    assert hasattr(custom_enum, "__strawberry_definition__")


def test_graphql_builder_static_mode_and_context_injection():
    from graphinate import SchemaMode, model
    from graphinate.builders import GraphQLBuilder, NetworkxBuilder

    m = model("StaticModel")

    @m.node(type_="user")
    def users():
        yield "alice"

    @m.node(type_="post", parent_type="user")
    def posts(user_id):
        yield f"{user_id}_post1"

    builder = GraphQLBuilder(m, mode=SchemaMode.STATIC)
    schema = builder.build()

    query = """
    {
      graph { name nodeCount }
      nodes {
        __typename
        type
        label
        neighbors(children: true) {
          __typename
          type
          label
        }
        edges {
          source { label }
          target { label }
        }
      }
    }
    """
    result = schema.execute_sync(query)
    assert result.errors is None
    assert result.data["graph"] == {"name": "StaticModel", "nodeCount": 2}
    nodes_by_type = {n["type"]: n for n in result.data["nodes"]}
    assert nodes_by_type["user"]["__typename"] == "GenericGraphNode"
    assert nodes_by_type["user"]["neighbors"] == [
        {"__typename": "GenericGraphNode", "type": "post", "label": "alice_post1"}
    ]
    assert len(nodes_by_type["user"]["edges"]) == 1

    # Verify context injection overrides builder's graph with a custom graph
    m_override = model("InjectedContextGraph")

    @m_override.node(type_="user")
    def override_users():
        yield "bob"

    override_nx = NetworkxBuilder(m_override).build()
    ctx_result = schema.execute_sync(
        "{ graph { name } nodes { label } }",
        context_value={"graph": override_nx},
    )
    assert ctx_result.errors is None
    assert ctx_result.data == {
        "graph": {"name": "InjectedContextGraph"},
        "nodes": [{"label": "bob"}],
    }


